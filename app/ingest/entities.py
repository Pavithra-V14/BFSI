"""Entity allow-list extraction (spec 6.8): terms that must NOT be masked, found at ingestion.

Candidates come from four sources: NER (the large spaCy model through Presidio, behind the `ner`
callable), pattern extractors (acts and regulations, helplines, emails, URLs, IFSC, CIN, product
codes), curated seeds (regulators and the company name) and the document's own structure
(product names from the title and headings, names written next to a designation).

What happens to a candidate (the allow-list table keeps one row per variant):
- customer-specific document: every candidate is rejected automatically;
- policy or regulatory document: laws, regulators, organisations, places and helplines are
  auto-approved; everything else (people, product codes, ids) goes to a decide-tier question with
  the surrounding text; a confident yes is approved, the rest stay `pending` for the owner;
- a person's variants ("Rahul Sharma" -> "Mr. Sharma", "R. Sharma", "Sharma") are generated by
  fixed rules and reviewed as a group; the single-word variant is approved only when the reviewer
  ticks it, never automatically.

Matching is exact on normalised variants (`normalise_entity`): no fuzzy matching. Entries belong to
a document (`doc_id`), are removed when it is deleted, and only changed chunks are re-extracted;
a term already stored for the document is never stored twice, and a reviewed status is kept.
"""

from __future__ import annotations

import re
import unicodedata
import uuid
from collections.abc import Callable, Iterable
from dataclasses import dataclass
from datetime import datetime

from app.accounts.tokens import utc_text
from app.ingest.model import DocRequest

AUTO_APPROVE_PROBABILITY = 0.85  # [P] a "public term" answer this confident is approved
AUTO_KINDS = frozenset({"law", "regulator", "organisation", "place", "helpline"})
# An email address or web address is only a "helpline" when its domain is a curated seed (a
# regulator, or the company's own domain). Any other one is "contact": it always waits for the
# reviewer and is never put to a model question, because it could be personal.
PENDING_KINDS = frozenset({"contact"})
CONTEXT_CHARS = 160

# Regulator domains (a name matches the domain itself and any sub-domain of it).
SEED_DOMAINS = (
    "irdai.gov.in",
    "sebi.gov.in",
    "rbi.org.in",
    "npci.org.in",
    "amfiindia.com",
    "scores.gov.in",
)
# The company's own domain for the sample documents (spec 20); the real one is COMPANY_DOMAINS [T].
DEFAULT_COMPANY_DOMAINS = ("auravance.aura",)

SEED_REGULATORS = (
    "IRDAI",
    "SEBI",
    "RBI",
    "NPCI",
    "AMFI",
    "Insurance Regulatory and Development Authority of India",
    "Securities and Exchange Board of India",
    "Reserve Bank of India",
    "National Payments Corporation of India",
    "Association of Mutual Funds in India",
)
# The company used for the sample documents (spec 20). The real company name is set by the owner
# with `--company-name` [T].
DEFAULT_COMPANY_NAMES = ("AuraVance Digital FinTech Private Limited", "AuraVance")

NER_KINDS = {
    "PERSON": "person_in_policy",
    "ORG": "organisation",
    "GPE": "place",
    "LOC": "place",
    "LAW": "law",
    "EMAIL_ADDRESS": "contact",
    "URL": "contact",
    "PHONE_NUMBER": None,  # a number is never allow-listed on NER's word (it could be personal)
    "LOCATION": "place",
    "NRP": None,
}

Ner = Callable[[str], list[tuple[str, str]]]  # text -> [(entity text, NER label)]
Classify = Callable[[str, str], float | None]  # (term, context) -> probability of "public term"

_TITLES = ("mr", "mrs", "ms", "dr", "shri", "smt", "prof")
_ROLE_WORDS = (
    r"chief|head|nodal|principal|grievance|compliance|managing|director|officer|manager|"
    r"appointed|chairman|chairperson|ceo|cfo|cto|secretary|ombudsman"
)
_PERSON_BY_ROLE = re.compile(
    r"((?:Mr|Mrs|Ms|Dr|Shri|Smt|Prof)\.?[ \t]+)?"
    r"([A-Z][a-z]+(?:[ \t]+[A-Z]\.?)?(?:[ \t]+[A-Z][a-z]+)+)"
    r"\s*(?:,|-|–|—|\()\s*(?:the\s+)?(?=(?i:" + _ROLE_WORDS + r"))"
)
_NAME_LEAD_IN = frozenset(
    "contact please call write email by for to from note see dear attention sincerely regards "
    "thanks the our your her his their officer manager director head chief".split()
)
_EMAIL = re.compile(r"[\w.+-]+@[\w-]+(?:\.[\w-]+)+")
_URL = re.compile(r"(?:https?://|www\.)[^\s)>\],;]+")
_TOLL_FREE = re.compile(r"\b1(?:800|860)[ -]?\d{2,3}[ -]?\d{3,4}\b")
# A short helpline code (1930, 14447 ...) counts only right after a word like "helpline", "call" or
# "dial"; a bare four- or five-digit number is a year, an amount or a clause number.
_SHORT_CODE = re.compile(
    r"(?i:helpline|toll[- ]?free|dial|call)[^.\n]{0,40}?\b(1\d{3,5})\b(?![ -]?\d)"
)
_IFSC = re.compile(r"\b[A-Z]{4}0[A-Z0-9]{6}\b")
_CIN = re.compile(r"\b[LU]\d{5}[A-Z]{2}\d{4}[A-Z]{3}\d{6}\b")
_PRODUCT_CODE = re.compile(r"\b[A-Z]{2,6}[-/]\d{2,6}(?:[-/][A-Z0-9]+)?\b")
_LAW_WORD = re.compile(
    r"\b(Act|Regulations?|Rules|Guidelines|Master Direction|Master Directions|Circular)\b"
    r"(?:,?\s*((?:19|20)\d{2}))?"
)
_CONNECTORS = {"of", "and", "for", "the", "on", "in"}
_PRODUCT_NOUNS = (
    "plan|policy|scheme|fund|account|card|loan|cover|insurance|facility|product|assurance"
)
_PRODUCT_HEADING = re.compile(rf"\b(?:{_PRODUCT_NOUNS})$", re.IGNORECASE)
_CLAUSE_PREFIX = re.compile(
    r"^\s*(?:(?:section|clause|article)\s+)?\d+[A-Za-z]?(?:\.\d+)*[.)]?\s*", re.I
)


_ARTICLES = re.compile(r"^(?:the|a|an)\s+", re.IGNORECASE)


def clean_ner_text(text: str, kind: str) -> str | None:
    """A NER hit as a candidate, or None when it is clearly not a name. NER on a policy document
    returns table fragments ("Associates | Chartered Accountants"), whole phrases ("a Current Ratio
    of at least 1.20"), lower-case words and one-word "people" ("Borrower"). Those are dropped here
    (a real one is still found by the pattern, seed and role rules); a leading "the" is removed."""
    text = _ARTICLES.sub("", " ".join(text.split()))
    words = text.split()
    if not text or "|" in text or len(words) > 8 or len(text) > 80:
        return None
    if not (text[0].isupper() or text[0].isdigit()) or not any(ch.isalpha() for ch in text):
        return None
    if kind == "person_in_policy" and len(words) < 2:
        return None
    return text


def domain_is_seeded(contact: str, domains: Iterable[str]) -> bool:
    """True when an email address or web address belongs to one of the curated domains (the
    domain itself or a sub-domain of it)."""
    text = contact.strip().lower()
    host = text.rsplit("@", 1)[1] if "@" in text else re.sub(r"^[a-z]+://", "", text)
    host = re.split(r"[/:?#]", host, maxsplit=1)[0].removeprefix("www.").strip(".")
    return any(host == d or host.endswith("." + d) for d in domains)


def normalise_entity(text: str) -> str:
    """The one rule for comparing entity text: NFKC, case-folded, whitespace collapsed, and
    quotes, commas and brackets trimmed from the ends. Matching is exact on this form."""
    folded = unicodedata.normalize("NFKC", text).casefold()
    return " ".join(folded.split()).strip(" \t\"'`,;:()[]")


@dataclass(frozen=True)
class Candidate:
    text: str
    kind: str  # a key of app.gateway.questions.ENTITY_KINDS
    context: str  # the surrounding text, for the decider and the reviewer
    source: str  # ner | pattern | seed | structure


@dataclass(frozen=True)
class Variant:
    text: str
    single_word: bool = False


def _context(text: str, start: int, end: int) -> str:
    return " ".join(text[max(0, start - CONTEXT_CHARS) : end + CONTEXT_CHARS].split())


_LEAD_WORDS = re.compile(
    r"(?:(?:under|as|per|by|with|see|in|of|the|and|for|on|to|from|pursuant|subject|refer|"
    r"within|at|any|all|this|that)\s+)+",
    re.IGNORECASE,
)


def _law_spans(text: str) -> Iterable[tuple[int, int]]:
    """(start, end) of "<Capitalised words> Act, 1938"-style names, without lead-in words."""
    for found in _LAW_WORD.finditer(text):
        start, taken = found.start(), 0
        line_start = text.rfind("\n", 0, found.start()) + 1  # never reach into the line above
        for word in reversed(list(re.finditer(r"\S+", text[line_start : found.start()]))):
            token = word.group().strip(",;:()\"'")
            if taken >= 8 or not token or word.group()[-1] in ".!?:;":
                break  # a word ending a sentence belongs to the sentence before
            if token[0].isupper() or token.lower() in _CONNECTORS:
                start, taken = line_start + word.start(), taken + 1
            else:
                break
        lead = _LEAD_WORDS.match(text[start : found.start()])
        if lead:
            start += lead.end()
        if start < found.start():  # a bare "Act" with nothing before it is not a name
            yield start, found.end()


def extract_candidates(
    chunks: Iterable[tuple[str, tuple[str, ...]]],
    request: DocRequest,
    ner: Ner,
    company_names: Iterable[str] = DEFAULT_COMPANY_NAMES,
    company_domains: Iterable[str] = DEFAULT_COMPANY_DOMAINS,
) -> list[Candidate]:
    """Candidates from the text and headings of the given chunks, first sighting of each term."""
    found: dict[tuple[str, str], Candidate] = {}
    seeded_domains = tuple(
        d.lower().strip() for d in (*SEED_DOMAINS, *company_domains) if d.strip()
    )

    def add(text: str, kind: str, context: str, source: str) -> None:
        text = " ".join(text.split()).strip(" ,;:.\"'")
        if len(text) < 2:
            return
        if kind == "contact" and domain_is_seeded(text, seeded_domains):
            kind = "helpline"
        found.setdefault((normalise_entity(text), kind), Candidate(text, kind, context, source))

    seeds = [(name, "regulator") for name in SEED_REGULATORS]
    seeds += [(name, "organisation") for name in company_names]
    headings: set[str] = set()
    for text, heading_path in chunks:
        headings.update(heading_path)
        for label_text, label in ner(text):
            kind = NER_KINDS.get(label)
            label_text = clean_ner_text(label_text, kind) if kind else None
            if kind and label_text:
                position = text.find(label_text)
                add(
                    label_text,
                    kind,
                    _context(text, max(position, 0), position + len(label_text)),
                    "ner",
                )
        for pattern, kind in (
            (_EMAIL, "contact"),
            (_URL, "contact"),
            (_TOLL_FREE, "helpline"),
            (_IFSC, "product"),
            (_CIN, "product"),
            (_PRODUCT_CODE, "product"),
        ):
            for match in pattern.finditer(text):
                add(match.group(), kind, _context(text, match.start(), match.end()), "pattern")
        for match in _SHORT_CODE.finditer(text):
            add(match.group(1), "helpline", _context(text, match.start(), match.end()), "pattern")
        for start, end in _law_spans(text):
            add(text[start:end], "law", _context(text, start, end), "pattern")
        for match in _PERSON_BY_ROLE.finditer(text):
            words = match.group(2).split()
            while len(words) > 2 and words[0].casefold() in _NAME_LEAD_IN:
                words = words[1:]
            if words[0].casefold() in _NAME_LEAD_IN:
                continue  # "Contact Officer, ..." is not a person
            name = ((match.group(1) or "") + " ".join(words)).strip()
            add(name, "person_in_policy", _context(text, match.start(), match.end()), "structure")
        for name, kind in seeds:
            for match in re.finditer(rf"(?<![\w]){re.escape(name)}(?![\w])", text):
                add(name, kind, _context(text, match.start(), match.end()), "seed")
    if request.title:
        add(request.title, "product", request.title, "structure")
    for heading in headings:
        bare = _CLAUSE_PREFIX.sub("", heading).strip()
        if bare and _PRODUCT_HEADING.search(bare):
            add(bare, "product", heading, "structure")
    return list(found.values())


def person_variants(name: str) -> list[Variant]:
    """Fixed rules (spec 6.8 step 2): "Rahul Sharma" -> "Rahul Sharma", "Mr. Sharma",
    "R. Sharma", "Sharma". A title in the name (Dr., Ms. ...) is kept in the "<title> <surname>"
    form; with none, "Mr." is used. The surname alone is the single-word variant."""
    words = name.split()
    title = None
    if words and words[0].rstrip(".").casefold() in _TITLES:
        title = (
            words[0] if words[0].endswith(".") else words[0] + ("." if len(words[0]) <= 3 else "")
        )
        words = words[1:]
    if len(words) < 2:
        return [Variant(" ".join(words), single_word=len(words) == 1)] if words else []
    first, surname = words[0], words[-1]
    variants = [
        Variant(" ".join(words)),
        *([Variant(f"{title} {' '.join(words)}")] if title else []),
        Variant(f"{title or 'Mr.'} {surname}"),
        Variant(f"{first[0].upper()}. {surname}"),
        Variant(surname, single_word=True),
    ]
    seen: set[str] = set()
    unique = []
    for variant in variants:
        key = normalise_entity(variant.text)
        if key not in seen:
            seen.add(key)
            unique.append(variant)
    return unique


def variants_of(candidate: Candidate) -> list[Variant]:
    if candidate.kind == "person_in_policy":
        return person_variants(candidate.text)
    return [Variant(candidate.text)]


@dataclass
class RecordResult:
    approved: int = 0
    pending: int = 0
    rejected: int = 0
    existing: int = 0


def record_candidates(
    db,
    request: DocRequest,
    candidates: Iterable[Candidate],
    classify: Classify | None,
    now: datetime,
) -> RecordResult:
    """Write the allow-list rows for the candidates. The caller opens the transaction."""
    result = RecordResult()
    stored = {
        normalise_entity(row[0])
        for row in db.query_all(
            "SELECT text FROM allowlist_entities WHERE doc_id = ?", (request.doc_id,)
        )
    }
    stamp = utc_text(now)

    def insert(variant: Variant, kind: str, status: str) -> None:
        key = normalise_entity(variant.text)
        if not key:
            return
        if key in stored:
            result.existing += 1
            return
        stored.add(key)
        approved_at = stamp if status == "approved" else None
        db.execute(
            "INSERT INTO allowlist_entities "
            "(id, doc_id, text, entity_type, status, approved_by, approved_at, access_role) "
            "VALUES (?, ?, ?, ?, ?, NULL, ?, ?)",
            (
                str(uuid.uuid4()),
                request.doc_id,
                variant.text,
                kind,
                status,
                approved_at,
                request.access_role,
            ),
        )
        setattr(result, status, getattr(result, status) + 1)

    for candidate in candidates:
        variants = variants_of(candidate)
        if request.doc_type == "customer-specific":
            status = "rejected"
        elif candidate.kind in AUTO_KINDS:
            status = "approved"
        elif candidate.kind in PENDING_KINDS:
            status = "pending"  # never auto-approved, never put to a model
        else:
            probability = classify(candidate.text, candidate.context) if classify else None
            confident = probability is not None and probability >= AUTO_APPROVE_PROBABILITY
            status = "approved" if confident else "pending"
        for variant in variants:
            # A single-word variant is approved only when the reviewer ticks it.
            variant_status = "pending" if variant.single_word and status == "approved" else status
            insert(variant, candidate.kind, variant_status)
    return result


def presidio_ner() -> Ner:
    """The real NER: Presidio with the large spaCy model. Needs requirements-ingest.txt and
    `python -m spacy download en_core_web_lg`; imported only when used (admin machine)."""
    from presidio_analyzer import AnalyzerEngine
    from presidio_analyzer.nlp_engine import NlpEngineProvider

    provider = NlpEngineProvider(
        nlp_configuration={
            "nlp_engine_name": "spacy",
            "models": [{"lang_code": "en", "model_name": "en_core_web_lg"}],
        }
    )
    engine = AnalyzerEngine(nlp_engine=provider.create_engine(), supported_languages=["en"])
    wanted = ["PERSON", "ORGANIZATION", "LOCATION", "EMAIL_ADDRESS", "URL", "PHONE_NUMBER"]

    def ner(text: str) -> list[tuple[str, str]]:
        found = []
        for hit in engine.analyze(text=text, language="en", entities=wanted):
            label = "ORG" if hit.entity_type == "ORGANIZATION" else hit.entity_type
            found.append((text[hit.start : hit.end], label))
        return found

    return ner
